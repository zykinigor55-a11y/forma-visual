import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from 'playwright';

const browser=await chromium.launch({headless:true});
const base='http://127.0.0.1:3000';
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
const head=async file=>{
 const response=await page.request.head(base+'/assets/landscape-models/'+file);
 assert.equal(response.status(),200,file+' not served');
 if(file.endsWith('.glb'))assert.match(response.headers()['content-type'],/model\/gltf-binary/);
};
try{
 await page.goto(base+'/forma-landscape-3d.html',{waitUntil:'domcontentloaded',timeout:30000});
 await page.waitForFunction(()=>document.querySelector('#status')?.textContent.includes('3D-конструктор готов'),null,{timeout:45000});
 assert.equal(await page.locator('#loadError').isVisible(),false);
 assert.equal(await page.locator('#sceneQuickTools').isVisible(),true);
 await page.locator('[data-quick-tool="plant"]').click({timeout:20000});
 assert.equal(await page.locator('#library [data-item]').count(),18);
 await page.locator('#catalogSearch').fill('берёза');
 assert.equal(await page.locator('[data-item="birch"]').isVisible(),true);
 assert.equal(await page.locator('[data-item="pine"]').isVisible(),false);
 await page.locator('#catalogSearch').fill('');
 await page.locator('[data-catalog-filter="shrubs"]').click();
 assert.equal(await page.locator('[data-item="juniper"]').isVisible(),true);
 assert.equal(await page.locator('[data-item="pine"]').isVisible(),false);
 await page.locator('[data-quick-tool="surface"]').click();
 assert.equal(await page.locator('#library [data-item]').count(),15);
 await page.locator('[data-catalog-filter="pavers"]').click();
 assert.equal(await page.locator('[data-item="concrete-pavers"]').isVisible(),true);
 assert.equal(await page.locator('[data-item="pine-bark"]').isVisible(),false);
 await page.locator('[data-quick-tool="terrain"]').click();
 for(const id of ['brushRadius','brushStrength','brushSoftness','brushShape'])assert.equal(await page.locator('#'+id).isVisible(),true,id);
 await page.locator('#brushShape').selectOption('square');
 await page.locator('[data-item="flatten"]').click();
 await page.locator('[data-view="2d"]').click();
 const canvas=await page.locator('#viewport').boundingBox();
 const clickSite=async(x=.58,y=.48)=>page.mouse.click(canvas.x+canvas.width*x,canvas.y+canvas.height*y);

 // Licensed 40-object collection is a real editing tool, not a static mock.
 await page.locator('[data-tool="models40"]').click({timeout:20000});
 assert.equal(await page.locator('#library [data-item]').count(),40);
 assert.equal(await page.locator('[data-catalog-filter]').count(),7,'6 functional material/object categories + all');
 await page.locator('[data-catalog-filter="nature"]').click();
 assert.equal(await page.locator('[data-item="rock-grey"]').isVisible(),true);
 assert.equal(await page.locator('[data-item="street-lamp-one"]').isVisible(),false);
 await page.locator('[data-catalog-filter="all"]').click();
 await page.locator('#catalogSearch').fill('Костровая');
 assert.equal(await page.locator('[data-item="fire-pit"]').isVisible(),true);
 assert.equal(await page.locator('[data-item="pine"]').isVisible(),false);
 await page.locator('#catalogSearch').fill('');
 await page.locator('[data-item="rock-grey"]').click();
 const glbResponse=page.waitForResponse(r=>r.url().includes('/assets/landscape-models/rock-grey.glb')&&r.status()===200,{timeout:35000});
 await clickSite(.59,.39);
 await glbResponse;
 assert.ok(await page.evaluate(()=>JSON.parse(localStorage.getItem('forma-landscape-3d-extra-v1-landscape')||'[]').some(x=>x.type==='rock-grey'&&x.width===1.4)),'Measured 3D rock persisted with its source identity and exact footprint');
 for(const path of ['rock-grey.glb','fire-pit.glb','planter-large.glb','gallinera-chair.glb','street-lamp-two.glb','thumbs/rock-grey.webp','thumbs/street-lamp-two.webp'])await head(path);
 await page.locator('[data-tool="select"]').click();
 await page.locator('[data-tool="landscape"]').click();
 assert.equal(await page.locator('#library [data-item]').count(),7);
 for(const item of ['fern','wild-shrub','periwinkle'])assert.equal(await page.locator('[data-item="'+item+'"]').count(),1);
 await page.locator('[data-item="fern"]').click();
 await clickSite(.58,.31);
 assert.ok(await page.evaluate(()=>JSON.parse(localStorage.getItem('forma-landscape-3d-extra-v1-landscape')||'[]').some(x=>x.type==='fern')),'fern position persisted as 3D object');
 await page.locator('[data-tool="furniture"]').click();
 await page.locator('[data-item="outdoor-dining"]').click();
 await clickSite(.62,.55);
 assert.ok(await page.evaluate(()=>JSON.parse(localStorage.getItem('forma-landscape-3d-extra-v1-landscape')||'[]').some(x=>x.type==='outdoor-dining')),'PBR furniture persists in scene');
 await page.locator('[data-quick-tool="plant"]').click();
 await page.locator('[data-item="pine"]').click();
 await clickSite(.43,.34);
 assert.ok(await page.evaluate(()=>JSON.parse(localStorage.getItem('forma-landscape-masterplan-v1-landscape')||'{}').objects?.some(x=>x.catalogId==='pine')),'tree coordinates persisted in real metre project');
 for(const name of ['pine.glb','fern.glb','outdoor-dining.glb','periwinkle.glb','picnic-table.glb','thumbs/outdoor-dining.webp'])await head(name);
 await mkdir('artifacts/landscape-editor',{recursive:true});
 await page.screenshot({path:'artifacts/landscape-editor/3d-fast-asset-catalog.png'});
 assert.deepEqual(errors,[],'Editor must not have JavaScript errors');
 console.log('PASS: 40 licensed PBR GLBs, editable measured placement, 6 searchable groups, all 15 surfaces, soft terrain brush');
}finally{await browser.close()}
